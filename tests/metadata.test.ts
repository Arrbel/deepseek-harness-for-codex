// Regression net for ADR-0001: `package.json` name/version is the single source of truth,
// and every other version fact is derived by scripts/version-sync.mjs and enforced by
// scripts/check-metadata.mjs.
//
// Every case below tampers with exactly one fact in an in-memory snapshot of this
// checkout and asserts the gate reports it. If any of these cases passes while the gate
// is broken, the distribution regression that produced `0.3.1` silently installed
// alongside `0.4.0` can return unnoticed.

import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import {
  MARKETPLACE_REL,
  MCP_SERVER_NAME,
  PLUGIN_DIR_REL,
  PLUGIN_ENTRY_REL,
  REQUIRED_PACKAGE_FILES,
  ROOT_MCP_REL,
  ROOT_PLUGIN_REL,
  VERSION_TS_REL,
  evaluateMetadata,
  expectedArtifacts,
  externalImports,
  formatFindings,
  renderEmbeddedPluginJson,
  renderMcpJson,
  renderRootPluginJson,
  sha256,
} from "../scripts/lib/metadata.mjs";
import type { MetadataSnapshot } from "../scripts/lib/metadata.mjs";
import { readRepoSnapshot } from "../scripts/lib/repo-snapshot.mjs";
import type { RepoSnapshot } from "../scripts/lib/repo-snapshot.mjs";
import { pluginPayloadExists, probePluginLaunch } from "../scripts/lib/self-contained-probe.mjs";
import "./support/isolation.js";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const realSnapshot: RepoSnapshot = await readRepoSnapshot(repoRoot);
const payloadExists = await pluginPayloadExists(repoRoot);

function cloneSnapshot(snapshot: MetadataSnapshot): MetadataSnapshot {
  return {
    manifest: structuredClone(snapshot.manifest),
    lock: structuredClone(snapshot.lock),
    marketplace: structuredClone(snapshot.marketplace),
    texts: new Map(snapshot.texts),
    hashes: new Map(snapshot.hashes),
    sourceHashes: new Map(snapshot.sourceHashes),
    listings: new Map(snapshot.listings),
    distImports: new Map(snapshot.distImports),
  };
}

function currentVersion(snapshot: MetadataSnapshot): string {
  return snapshot.manifest.version ?? "0.0.0";
}

/** Marks the generated payload as present, independent of what is on disk right now. */
function seedPayloadPresence(snapshot: MetadataSnapshot): void {
  const artifacts = expectedArtifacts({
    name: snapshot.manifest.name ?? "",
    version: currentVersion(snapshot),
  });
  snapshot.listings.set(
    PLUGIN_DIR_REL,
    artifacts
      .map((artifact) => artifact.path)
      .filter((path) => path.startsWith(`${PLUGIN_DIR_REL}/`)),
  );
}

function findingsFor(snapshot: MetadataSnapshot) {
  return evaluateMetadata(snapshot);
}

const pluginManifestRel = `${PLUGIN_DIR_REL}/.codex-plugin/plugin.json`;
const pluginMcpRel = `${PLUGIN_DIR_REL}/.mcp.json`;
const pluginEntryRel = `${PLUGIN_DIR_REL}/${PLUGIN_ENTRY_REL}`;

interface Mutation {
  name: string;
  code: string;
  path: string;
  apply: (snapshot: MetadataSnapshot) => void;
}

const mutations: Mutation[] = [
  {
    name: "a hand-edited embedded plugin version (the 0.3.1 incident)",
    code: "generated-drift",
    path: pluginManifestRel,
    apply: (snapshot) => {
      seedPayloadPresence(snapshot);
      snapshot.texts.set(
        pluginManifestRel,
        renderEmbeddedPluginJson({ name: "deepseek-harness", version: "0.3.1" }),
      );
    },
  },
  {
    name: "the root plugin manifest version",
    code: "generated-drift",
    path: ROOT_PLUGIN_REL,
    apply: (snapshot) => {
      snapshot.texts.set(
        ROOT_PLUGIN_REL,
        renderRootPluginJson({ name: snapshot.manifest.name ?? "", version: "0.3.1" }),
      );
    },
  },
  {
    name: "the generated src/version.ts constants",
    code: "generated-drift",
    path: VERSION_TS_REL,
    apply: (snapshot) => {
      snapshot.texts.set(
        VERSION_TS_REL,
        [
          "// generated by scripts/version-sync.mjs from package.json; do not edit by hand.",
          "",
          'export const PACKAGE_NAME = "deepseek-harness-for-codex";',
          'export const PACKAGE_VERSION = "0.3.1";',
          "",
        ].join("\n"),
      );
    },
  },
  {
    name: "an npx self-reference in .mcp.json (pre-publish deadlock shape)",
    code: "self-reference-pin",
    path: ROOT_MCP_REL,
    apply: (snapshot) => {
      snapshot.texts.set(
        ROOT_MCP_REL,
        `${JSON.stringify(
          {
            mcpServers: {
              [MCP_SERVER_NAME]: {
                command: "npx",
                args: [
                  "--yes",
                  "--package=deepseek-harness-for-codex@0.3.1",
                  "--",
                  "deepseek-harness-for-codex",
                ],
              },
            },
          },
          null,
          2,
        )}\n`,
      );
    },
  },
  {
    name: "the package.json version without regenerating the derived files",
    code: "generated-drift",
    path: VERSION_TS_REL,
    apply: (snapshot) => {
      snapshot.manifest.version = "0.5.0";
    },
  },
  {
    name: "the package-lock.json version",
    code: "lock-drift",
    path: "package-lock.json",
    apply: (snapshot) => {
      const root = (snapshot.lock?.packages ?? {})[""];
      if (root !== undefined) root.version = "0.3.1";
      if (snapshot.lock !== null) snapshot.lock.version = "0.3.1";
    },
  },
  {
    name: "the npm files[] whitelist (dropping the plugin payload)",
    code: "package-files-missing",
    path: "package.json",
    apply: (snapshot) => {
      snapshot.manifest.files = (snapshot.manifest.files ?? []).filter((entry) => entry !== "skills/");
    },
  },
  {
    name: "the check script dropping the metadata gate",
    code: "script-gate-missing",
    path: "package.json",
    apply: (snapshot) => {
      snapshot.manifest.scripts = {
        ...(snapshot.manifest.scripts ?? {}),
        check: "npm run typecheck && npm run test && npm run build",
      };
    },
  },
  {
    name: "the marketplace source path",
    code: "marketplace-source-invalid",
    path: MARKETPLACE_REL,
    apply: (snapshot) => {
      const entry = snapshot.marketplace?.plugins?.[0];
      if (entry?.source !== undefined) entry.source.path = "./plugins/other";
    },
  },
  {
    name: "a hand-added file inside the generated plugin directory",
    code: "generated-extra-file",
    path: `${PLUGIN_DIR_REL}/hand-added.txt`,
    apply: (snapshot) => {
      seedPayloadPresence(snapshot);
      snapshot.listings.set(PLUGIN_DIR_REL, [
        ...(snapshot.listings.get(PLUGIN_DIR_REL) ?? []),
        `${PLUGIN_DIR_REL}/hand-added.txt`,
      ]);
    },
  },
  {
    name: "a plugin payload that no longer matches the built bundle",
    code: "generated-drift",
    path: pluginEntryRel,
    apply: (snapshot) => {
      seedPayloadPresence(snapshot);
      snapshot.sourceHashes.set("dist/bin.mjs", "a".repeat(64));
      snapshot.hashes.set(pluginEntryRel, "b".repeat(64));
    },
  },
  {
    name: "a plugin payload missing after the build",
    code: "generated-missing",
    path: pluginEntryRel,
    apply: (snapshot) => {
      seedPayloadPresence(snapshot);
      snapshot.sourceHashes.set("dist/bin.mjs", "a".repeat(64));
      snapshot.hashes.set(pluginEntryRel, null);
    },
  },
  {
    name: "a plugin payload kept without its source",
    code: "generated-orphan",
    path: pluginEntryRel,
    apply: (snapshot) => {
      seedPayloadPresence(snapshot);
      snapshot.sourceHashes.set("dist/bin.mjs", null);
      snapshot.hashes.set(pluginEntryRel, "c".repeat(64));
    },
  },
  {
    name: "an edited root SKILL without regenerating the plugin copy",
    code: "generated-drift",
    path: `${PLUGIN_DIR_REL}/skills/deepseek-harness/SKILL.md`,
    apply: (snapshot) => {
      seedPayloadPresence(snapshot);
      snapshot.sourceHashes.set("skills/deepseek-harness/SKILL.md", sha256("edited skill"));
      snapshot.hashes.set(`${PLUGIN_DIR_REL}/skills/deepseek-harness/SKILL.md`, sha256("old copy"));
    },
  },
  {
    name: "a README pinning an older release",
    code: "docs-stale-version",
    path: "README.md",
    apply: (snapshot) => {
      snapshot.texts.set(
        "README.md",
        `${snapshot.texts.get("README.md") ?? ""}\ncodex plugin add deepseek-harness-for-codex@0.3.1\n`,
      );
    },
  },
  {
    name: "a README pinning the current release instead of deriving it",
    code: "docs-hardcoded-version",
    path: "README.md",
    apply: (snapshot) => {
      const pinned = snapshot.manifest.version ?? "0.0.0";
      snapshot.texts.set(
        "README.md",
        `${snapshot.texts.get("README.md") ?? ""}\nnpm run version:sync # deepseek-harness-for-codex@${pinned}\n`,
      );
    },
  },
  {
    name: "the .gitignore rule that keeps the generated plugin directory out of git",
    code: "plugin-dir-not-ignored",
    path: ".gitignore",
    apply: (snapshot) => {
      snapshot.texts.set(".gitignore", "dist/\nnode_modules/\n");
    },
  },
  {
    name: "the self-contained bundle falling back to node_modules",
    code: "dist-external-import",
    path: "dist/bin.mjs",
    apply: (snapshot) => {
      snapshot.distImports.set("dist/bin.mjs", ["@modelcontextprotocol/sdk/server/mcp.js"]);
    },
  },
];

describe("metadata single source of truth", () => {
  it("keeps this checkout consistent with package.json", () => {
    const findings = findingsFor(realSnapshot);
    expect(findings, formatFindings(findings)).toEqual([]);
  });

  it("accepts a fresh clone that has never generated the plugin payload", () => {
    const fresh = cloneSnapshot(realSnapshot);
    fresh.listings.set(PLUGIN_DIR_REL, []);
    for (const [rel] of fresh.hashes) {
      if (rel.startsWith(`${PLUGIN_DIR_REL}/`)) fresh.hashes.set(rel, null);
    }
    fresh.sourceHashes.set("dist/bin.mjs", null);
    fresh.distImports.clear();
    const findings = findingsFor(fresh);
    expect(findings, formatFindings(findings)).toEqual([]);
  });

  it("reports a payload deleted after the build", () => {
    const deleted = cloneSnapshot(realSnapshot);
    deleted.listings.set(PLUGIN_DIR_REL, []);
    deleted.sourceHashes.set("dist/bin.mjs", sha256("built bundle"));
    const findings = findingsFor(deleted);
    expect(findings.map((item) => item.code)).toContain("plugin-payload-missing");
  });

  it("derives every generated artifact from package.json", () => {
    const artifacts = expectedArtifacts({
      name: realSnapshot.manifest.name ?? "",
      version: realSnapshot.manifest.version ?? "",
    });
    const paths = artifacts.map((artifact) => artifact.path);
    expect(paths).toContain(ROOT_MCP_REL);
    expect(paths).toContain(ROOT_PLUGIN_REL);
    expect(paths).toContain(VERSION_TS_REL);
    expect(paths).toContain(pluginManifestRel);
    expect(paths).toContain(pluginMcpRel);
    expect(paths).toContain(pluginEntryRel);
    expect(paths).toContain(`${PLUGIN_DIR_REL}/skills/deepseek-harness/SKILL.md`);
  });

  it("ships the plugin payload in the npm files[] whitelist", () => {
    const files = realSnapshot.manifest.files ?? [];
    for (const required of REQUIRED_PACKAGE_FILES) {
      const present = files.some(
        (entry) => entry === required || entry === required.replace(/\/$/, ""),
      );
      expect(present, `files[] is missing ${required}`).toBe(true);
    }
  });

  it("launches the plugin through node without npx", () => {
    const text = renderMcpJson();
    expect(text).not.toMatch(/\bnpx\b/);
    const parsed = JSON.parse(text) as {
      mcpServers: Record<string, { command: string; args: string[]; cwd: string }>;
    };
    const server = parsed.mcpServers[MCP_SERVER_NAME];
    expect(server?.command).toBe("node");
    expect(server?.args).toEqual([`./${PLUGIN_ENTRY_REL}`]);
    expect(server?.cwd).toBe(".");
  });

  for (const mutation of mutations) {
    it(`detects ${mutation.name}`, () => {
      const mutated = cloneSnapshot(realSnapshot);
      mutation.apply(mutated);
      const findings = findingsFor(mutated);
      expect(findings.map((item) => item.code), formatFindings(findings)).toContain(mutation.code);
      expect(
        findings.some((item) => item.path === mutation.path),
        formatFindings(findings),
      ).toBe(true);
    });
  }

  it("reports a version bump across every derived file at once", () => {
    const mutated = cloneSnapshot(realSnapshot);
    mutated.manifest.version = "0.5.0";
    const findings = findingsFor(mutated);
    expect(findings.length).toBeGreaterThanOrEqual(4);
  });
});

describe("externalImports", () => {
  it("ignores specifiers that only appear inside generated code strings", () => {
    const codegen =
      'const template = `require("ajv-formats/dist/formats").${exportName}`;\n' +
      'const other = codegen_1._`require("ajv/dist/runtime/validation_error").default`;\n';
    expect(externalImports(codegen)).toEqual([]);
  });

  it("detects a runtime import in the module header and ignores node builtins", () => {
    const bundle = 'import { z } from "zod";\nimport { createHash } from "node:crypto";\n';
    expect(externalImports(bundle)).toEqual(["zod"]);
  });
});

describe.runIf(payloadExists)("generated plugin payload", () => {
  it("starts from its own directory with no node_modules and exposes the tool catalogue", async () => {
    const probe = await probePluginLaunch({ root: repoRoot });
    expect(probe.error).toBeNull();
    expect(probe.missingTools).toEqual([]);
    expect(probe.tools).toContain("doctor");
  }, 60_000);

  it("reports the version from package.json over the MCP handshake", async () => {
    const probe = await probePluginLaunch({ root: repoRoot });
    expect(probe.serverName).toBe(realSnapshot.manifest.name);
    expect(probe.serverVersion).toBe(realSnapshot.manifest.version);
  }, 60_000);
});
