function textArtifact(path, text) {
  return { path, kind: "text", text, sha256: sha256(text) };
}

function copyArtifact(path, copyFrom) {
  return { path, kind: "copy", copyFrom };
}

/**
 * Builds the complete expected state derived from the authoritative manifest.
 * @returns {Array<{path: string, kind: "text"|"copy", text?: string, copyFrom?: string, sha256?: string}>}
 */
export function expectedArtifacts({ name, version, pluginName = PLUGIN_NAME }) {
  const artifacts = [
    textArtifact(VERSION_TS_REL, renderVersionTs({ name, version })),
    textArtifact(ROOT_MCP_REL, renderMcpJson()),
    textArtifact(ROOT_PLUGIN_REL, renderRootPluginJson({ name, version })),
    textArtifact(`${PLUGIN_DIR_REL}/.mcp.json`, renderMcpJson()),
    textArtifact(
      `${PLUGIN_DIR_REL}/.codex-plugin/plugin.json`,
      renderEmbeddedPluginJson({ name: pluginName, version }),
    ),
  ];
  for (const source of PLUGIN_COPY_SOURCES) {
    artifacts.push(copyArtifact(`${PLUGIN_DIR_REL}/${source}`, source));
  }
  for (const file of DIST_FILES) {
    artifacts.push(copyArtifact(`${PLUGIN_DIR_REL}/dist/${file}`, `dist/${file}`));
  }
  return artifacts;
}

/** Text paths the snapshot reader must capture. */
export function textPathsFor(name, version, pluginName = PLUGIN_NAME) {
  const expected = expectedArtifacts({ name, version, pluginName }).filter(
    (artifact) => artifact.kind === "text",
  );
  return [...new Set([...expected.map((artifact) => artifact.path), ...SCANNED_TEXT_RELS])].sort();
}

/** Binary/content paths the snapshot reader must hash. */
export function hashPathsFor(name, version, pluginName = PLUGIN_NAME) {
  const expected = expectedArtifacts({ name, version, pluginName });
  const copies = expected
    .filter((artifact) => artifact.kind === "copy")
    .map((artifact) => artifact.path);
  const sources = expected
    .filter((artifact) => artifact.kind === "copy")
    .map((artifact) => artifact.copyFrom);
  return [...new Set([...copies, ...sources])].sort();
}

function finding(code, path, message) {
  return { code, path, message };
}

function expectedHash(artifact, sourceHashes) {
  if (artifact.kind === "text") return artifact.sha256;
  return sourceHashes.get(artifact.copyFrom) ?? null;
}

function hasIgnoredPluginDir(gitignoreText) {
  if (typeof gitignoreText !== "string") return false;
  return gitignoreText
    .split(/\r?\n/)
    .map((line) => line.trim())
    .some((line) => {
      if (line === "" || line.startsWith("#")) return false;
      const rule = line.replace(/^\//, "").replace(/\/$/, "");
      return rule === PLUGIN_DIR_REL || rule === "plugins" || rule === `${PLUGIN_DIR_REL}/**`;
    });
}

/**
 * Extracts *static, line-leading* import specifiers from a bundle.
 *
 * Only the module header of a bundler output counts: specifiers that appear inside
 * string literals (ajv's codegen emits `require("ajv-formats/dist/formats")` as text)
 * are not runtime imports of the bundle. The authoritative self-containment proof is the
 * runtime probe (scripts/lib/self-contained-probe.mjs); this scan is the cheap static net
 * that fires when the bundling configuration is lost.
 */
export function externalImports(text) {
  const specifiers = new Set();
  const patterns = [
    /^import\s[^\n"']*?from\s*["']([^"']+)["']/gm,
    /^import\s*["']([^"']+)["']/gm,
    /^export\s[^\n"']*?from\s*["']([^"']+)["']/gm,
  ];
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      const specifier = match[1];
      if (specifier === undefined) continue;
      if (specifier.startsWith(BUILTIN_PREFIX)) continue;
      if (specifier.startsWith(".") || specifier.startsWith("/")) continue;
      specifiers.add(specifier);
    }
  }
  return [...specifiers].sort();
}

/**
 * Evaluates one snapshot against the expected derived state.
 * @param {{
 *   manifest: {name?: string, version?: string, files?: string[], scripts?: Record<string, string>},
 *   lock: {version?: string, packages?: Record<string, {name?: string, version?: string}>}|null,
 *   marketplace: {plugins?: Array<{name?: string, source?: {source?: string, path?: string}}>}|null,
 *   texts: Map<string, string|null>,
 *   hashes: Map<string, string|null>,
 *   sourceHashes: Map<string, string|null>,
 *   listings: Map<string, string[]>,
 *   distImports: Map<string, string[]>,
 * }} snapshot
 * @returns {Array<{code: string, path: string, message: string}>}
 */
export function evaluateMetadata(snapshot) {
  const findings = [];
  const manifest = snapshot.manifest ?? {};
  const name = typeof manifest.name === "string" ? manifest.name : null;
  const version = typeof manifest.version === "string" ? manifest.version : null;

  if (name === null || version === null) {
    findings.push(
      finding("manifest-invalid", "package.json", "package.json must define a string name and version"),
    );
    return findings;
  }
  if (!/^\d+\.\d+\.\d+(?:[-+].+)?$/.test(version)) {
    findings.push(
      finding("version-not-semver", "package.json", `package.json version ${version} is not semver`),
    );
  }

  const text = (rel) => snapshot.texts?.get(rel) ?? null;
  const hash = (rel) => snapshot.hashes?.get(rel) ?? null;
  const artifacts = expectedArtifacts({ name, version });

  // The generated marketplace payload is git-ignored, so a fresh clone legitimately has
  // none. Absence is only accepted while nothing was built; once dist/ exists the payload
  // must exist too, and any non-empty payload must match exactly (that is what catches a
  // hand-edited copy before the build would silently regenerate it).
  const actualUnderPlugin = snapshot.listings?.get(PLUGIN_DIR_REL) ?? [];
  const payloadAbsent = actualUnderPlugin.length === 0;
  const distBuilt = snapshot.sourceHashes?.get("dist/bin.mjs") != null;
  if (payloadAbsent && distBuilt) {
    findings.push(
      finding(
        "plugin-payload-missing",
        `${PLUGIN_DIR_REL}/${PLUGIN_ENTRY_REL}`,
        `dist/ is built but the generated plugin payload is gone; run: npm run version:sync (or npm run build)`,
      ),
    );
  }

  for (const artifact of artifacts) {
    if (payloadAbsent && artifact.path.startsWith(`${PLUGIN_DIR_REL}/`)) continue;
    const actual =
      artifact.kind === "text"
        ? (() => {
            const content = text(artifact.path);
            return content === null ? null : sha256(content);
          })()
        : hash(artifact.path);
    const sourcePresent =
      artifact.kind === "text"
        ? true
        : snapshot.sourceHashes?.get(artifact.copyFrom) != null;

    if (!sourcePresent) {
      // Build output is not present yet (fresh clone): an absent copy is expected,
      // but a copy without its source means the generated payload is orphaned.
      if (actual != null) {
        findings.push(
          finding(
            "generated-orphan",
            artifact.path,
            `${artifact.path} exists while its source ${artifact.copyFrom} does not; run: npm run build`,
          ),
        );
      }
      continue;
    }
    if (actual === null || actual === undefined) {
      findings.push(
        finding("generated-missing", artifact.path, `${artifact.path} is missing; run: npm run build`),
      );
      continue;
    }
    const expected = expectedHash(artifact, snapshot.sourceHashes ?? new Map());
    if (expected === null) {
      findings.push(
        finding(
          "copy-source-missing",
          artifact.copyFrom,
          `copy source ${artifact.copyFrom} is missing, so ${artifact.path} cannot be verified`,
        ),
      );
      continue;
    }
    if (actual !== expected) {
      findings.push(
        finding(
          "generated-drift",
          artifact.path,
          `${artifact.path} does not match the state derived from package.json@${version}`,
        ),
      );
    }
  }

  // A generated descriptor must never self-reference the package through npx again.
  for (const rel of [ROOT_MCP_REL, `${PLUGIN_DIR_REL}/.mcp.json`]) {
    const content = text(rel);
    if (typeof content !== "string") continue;
    if (/\bnpx\b/.test(content)) {
      findings.push(
        finding(
          "self-reference-pin",
          rel,
          `${rel} launches through npx; the plugin must start self-contained with {"command":"node","args":["./${PLUGIN_ENTRY_REL}"],"cwd":"."}`,
        ),
      );
    }
    const pin = content.match(/deepseek-harness-for-codex@[^"'\s]+/);
    if (pin !== null) {
      findings.push(
        finding(
          "self-reference-pin",
          rel,
          `${rel} pins ${pin[0]}; installing the plugin must not depend on a published version of itself`,
        ),
      );
    }
  }

  // The generated plugin directory must contain exactly the expected files.
  const expectedUnderPlugin = new Set(
    artifacts
      .map((artifact) => artifact.path)
      .filter((path) => path.startsWith(`${PLUGIN_DIR_REL}/`)),
  );
  for (const path of actualUnderPlugin) {
    if (!expectedUnderPlugin.has(path)) {
      findings.push(
        finding(
          "generated-extra-file",
          path,
          `${path} is not produced by scripts/version-sync.mjs; the generated plugin directory must stay purely derived`,
        ),
      );
    }
  }

  // The npm package must still ship the plugin payload and the self-contained entry.
  const files = Array.isArray(manifest.files) ? manifest.files : [];
  for (const required of REQUIRED_PACKAGE_FILES) {
    const present = files.some((entry) => entry === required || entry === required.replace(/\/$/, ""));
    if (!present) {
      findings.push(
        finding("package-files-missing", "package.json", `package.json files[] must include ${required}`),
      );
    }
  }

  // The gate itself must stay wired.
  const scripts = manifest.scripts ?? {};
  for (const [script, needle] of Object.entries(REQUIRED_SCRIPT_GATES)) {
    const value = scripts[script];
    if (typeof value !== "string" || !value.includes(needle)) {
      findings.push(
        finding(
          "script-gate-missing",
          "package.json",
          `script "${script}" must invoke ${needle} (prepack/check must not bypass the metadata gate)`,
        ),
      );
    }
  }

  // package-lock.json must agree with the authoritative version.
  if (snapshot.lock === null || snapshot.lock === undefined) {
    findings.push(finding("lock-missing", "package-lock.json", "package-lock.json is missing"));
  } else {
    const root = snapshot.lock.packages?.[""] ?? {};
    if (root.version !== version || root.name !== name) {
      findings.push(
        finding(
          "lock-drift",
          "package-lock.json",
          `package-lock.json packages[""] is ${String(root.name)}@${String(root.version)}, expected ${name}@${version}`,
        ),
      );
    }
    if (snapshot.lock.version !== undefined && snapshot.lock.version !== version) {
      findings.push(
        finding(
          "lock-drift",
          "package-lock.json",
          `package-lock.json version is ${String(snapshot.lock.version)}, expected ${version}`,
        ),
      );
    }
  }

  // The marketplace must resolve to the generated plugin directory and expect the right version.
  const expectedPluginJson = text(`${PLUGIN_DIR_REL}/.codex-plugin/plugin.json`);
  const marketplace = snapshot.marketplace;
  if (marketplace === null || marketplace === undefined) {
    findings.push(finding("marketplace-missing", MARKETPLACE_REL, `${MARKETPLACE_REL} is missing`));
  } else {
    const entry = (marketplace.plugins ?? []).find((plugin) => plugin?.name === PLUGIN_NAME);
    if (entry === undefined) {
      findings.push(
        finding("marketplace-plugin-missing", MARKETPLACE_REL, `marketplace must expose plugin ${PLUGIN_NAME}`),
      );
    } else {
      const source = entry.source ?? {};
      if (source.source !== "local" || source.path !== `./${PLUGIN_DIR_REL}`) {
        findings.push(
          finding(
            "marketplace-source-invalid",
            MARKETPLACE_REL,
            `marketplace source must be {"source":"local","path":"./${PLUGIN_DIR_REL}"} so it resolves to the generated plugin directory`,
          ),
        );
      }
    }
  }

  // Version claims in user-facing docs must not be hardcoded.
  for (const rel of ["README.md", "README.en.md", "skills/deepseek-harness/SKILL.md"]) {
    const content = text(rel);
    if (typeof content !== "string") continue;
    const pattern = /(?:deepseek-harness-for-codex|deepseek-harness)@(\d+\.\d+\.\d+[0-9A-Za-z.+-]*)/g;
    for (const match of content.matchAll(pattern)) {
      const pinned = match[1];
      findings.push(
        finding(
          pinned === version ? "docs-hardcoded-version" : "docs-stale-version",
          rel,
          pinned === version
            ? `${rel} hardcodes ${match[0]}; describe the version without a pin (or use the generated local path) so docs cannot drift`
            : `${rel} pins ${match[0]} but package.json is ${version}`,
        ),
      );
    }
  }

  // The generated plugin directory must be ignored, otherwise it is committed twice.
  if (!hasIgnoredPluginDir(text(".gitignore"))) {
    findings.push(
      finding(
        "plugin-dir-not-ignored",
        ".gitignore",
        `.gitignore must ignore ${PLUGIN_DIR_REL} (generated, never hand-maintained)`,
      ),
    );
  }

  // The built entry must be self-contained: Codex copies the plugin into its own cache,
  // where the checkout's node_modules is unreachable.
  for (const [rel, imports] of snapshot.distImports ?? new Map()) {
    for (const specifier of imports) {
      findings.push(
        finding(
          "dist-external-import",
          rel,
          `${rel} imports ${specifier} at runtime; the copied plugin directory has no node_modules, so the bundle must inline runtime dependencies`,
        ),
      );
    }
  }

  return findings;
}

/** Renders a finding list for CLI output. */
export function formatFindings(findings) {
  return findings.map((item) => `- [${item.code}] ${item.path}: ${item.message}`).join("\n");
}
